    public static readonly IReadOnlyList<CurrencyInfo> All =
        Raw.Select(r => new CurrencyInfo(r.Code, r.Name, r.FlagCountry.ToLowerInvariant(), r.TimeZoneId, r.Lat, r.Lon))
           .OrderBy(c => c.Code, StringComparer.Ordinal)
           .ToList();

    private static readonly Dictionary<string, CurrencyInfo> ByCode =
        All.ToDictionary(c => c.Code, StringComparer.OrdinalIgnoreCase);

    public static CurrencyInfo? Find(string code) =>
        ByCode.TryGetValue(code, out var info) ? info : null;

    public static IEnumerable<CurrencyInfo> Search(string query)
    {
        if (string.IsNullOrWhiteSpace(query))
            return All;

        query = query.Trim();
        return All.Where(c =>
            c.Code.Contains(query, StringComparison.OrdinalIgnoreCase) ||
            c.Name.Contains(query, StringComparison.OrdinalIgnoreCase));
    }
